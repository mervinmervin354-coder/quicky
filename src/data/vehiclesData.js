export const calculateDistance = (cityA, cityB) => {
  if (!cityA || !cityB || !cityA.trim() || !cityB.trim() || cityA.trim().toLowerCase() === cityB.trim().toLowerCase()) return 0;
  
  const cleanA = cityA.trim();
  const cleanB = cityB.trim();

  const key1 = `${cleanA}-${cleanB}`;
  const key2 = `${cleanB}-${cleanA}`;
  if (DISTANCE_MATRIX[key1]) return DISTANCE_MATRIX[key1];
  if (DISTANCE_MATRIX[key2]) return DISTANCE_MATRIX[key2];

  for (const k of Object.keys(DISTANCE_MATRIX)) {
    const [a, b] = k.split('-');
    if (
      (cleanA.toLowerCase().includes(a.toLowerCase()) || a.toLowerCase().includes(cleanA.toLowerCase())) &&
      (cleanB.toLowerCase().includes(b.toLowerCase()) || b.toLowerCase().includes(cleanB.toLowerCase()))
    ) {
      return DISTANCE_MATRIX[k];
    }
  }

  let hash = 0;
  for (let i = 0; i < (cleanA + cleanB).length; i++) {
    hash += (cleanA + cleanB).charCodeAt(i);
  }
  return 35 + (hash % 145);
};
